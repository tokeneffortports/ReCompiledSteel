#!/usr/bin/env bash
# Linux / Steam Deck build of Real Steel. From Ubuntu (WSL is fine):
#   bash tools/build_linux.sh
#
# Needs the ReXGlue Linux SDK (REXSDK_LINUX_DIR, default /mnt/c/rexglue/linux-amd64
# or ~/rexglue/linux-amd64), clang 20, cmake, ninja, rsync, git, python3, and
# the game files in work/ (docs/building.md). The tree is mirrored into a
# directory on the Linux side (NTFS mounts are slow and lose exec bits) so
# rebuilds stay incremental, then the release folder is staged in
# release/ReCompiledSteel-linux-x64/ (+ .tar.gz): copy that to the Deck, run
# realsteel-setup there, add start.sh to Steam.
#
# The shader cache is generated by XenosRecomp. If generated/shader_cache.cpp
# already exists (a Windows build made it; the cache is platform-neutral) it
# is reused; otherwise run `python3 tools/shaders/setup_xenosrecomp.py` on
# the Linux side first or set RS_XENOSRECOMP.
set -euo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd -- "$SCRIPT_DIR/.." && pwd)"
SDK_SRC="${REXSDK_LINUX_DIR:-}"
if [[ -z "$SDK_SRC" ]]; then
    for candidate in /mnt/c/rexglue/linux-amd64 "$HOME/rexglue/linux-amd64"; do
        [[ -f "$candidate/lib/cmake/rexglue/rexglueConfig.cmake" ]] && SDK_SRC="$candidate" && break
    done
fi
BUILD_ROOT="${REALSTEEL_BUILD_ROOT:-$HOME/realsteel-deck-build}"
SDK="$BUILD_ROOT/rexglue/linux-amd64"
PROJ="$BUILD_ROOT/realsteelrecomp"
PRESET="${REALSTEEL_PRESET:-linux-amd64-release}"

if [[ ! -f "$ROOT/CMakeLists.txt" ]]; then
    echo "Could not locate the project above this script: $ROOT" >&2
    exit 1
fi
if [[ -z "$SDK_SRC" || ! -f "$SDK_SRC/lib/cmake/rexglue/rexglueConfig.cmake" ]]; then
    echo "ReXGlue Linux SDK not found. Set REXSDK_LINUX_DIR to the unpacked linux-amd64 SDK." >&2
    exit 1
fi
if [[ ! -f "$ROOT/work/game/default.xex" ]]; then
    echo "Game files not found in work/game (see docs/building.md, section 3)." >&2
    exit 1
fi

echo "== [1/5] Toolchain =="
missing=""
for tool in cmake ninja clang-20 rsync git python3; do
    command -v "$tool" >/dev/null 2>&1 || missing="$missing $tool"
done
if [[ -n "$missing" ]]; then
    echo "Missing tools:$missing" >&2
    echo "Install with: sudo apt-get install -y cmake ninja-build rsync git python3" >&2
    echo "and clang 20 from https://apt.llvm.org (sudo ./llvm.sh 20)." >&2
    exit 1
fi
clang-20 --version | head -1

echo "== [2/5] Mirroring the SDK =="
mkdir -p "$SDK"
rsync -a --delete "$SDK_SRC/" "$SDK/"
chmod +x "$SDK"/bin/* 2>/dev/null || true  # exec bits are lost on NTFS

echo "== [3/5] Mirroring the project =="
mkdir -p "$PROJ/generated"
cd "$ROOT"
rsync -a CMakeLists.txt CMakePresets.json realsteel_manifest.toml realsteel_overrides.toml "$PROJ/"
rsync -a --delete src thirdparty "$PROJ/"
rsync -a --delete --exclude='build' --exclude='build-*' tools "$PROJ/"
rsync -a --delete work/game work/tu "$PROJ/work/" --mkpath
rsync -a generated/rexglue.cmake "$PROJ/generated/"
if [[ -f generated/shader_cache.cpp ]]; then
    rsync -a generated/shader_cache.cpp "$PROJ/generated/"
fi
XR_ARGS=()
if [[ -n "${RS_XENOSRECOMP:-}" ]]; then
    XR_ARGS=(-DRS_XENOSRECOMP="$RS_XENOSRECOMP")
elif [[ -x "$ROOT/thirdparty/XenosRecomp/build/XenosRecomp/XenosRecomp" ]]; then
    XR_ARGS=(-DRS_XENOSRECOMP="$ROOT/thirdparty/XenosRecomp/build/XenosRecomp/XenosRecomp")
fi

echo "== [4/5] Configuring and building ($PRESET) =="
cd "$PROJ"
cmake --preset "$PRESET" -DCMAKE_PREFIX_PATH="$SDK" -DCMAKE_INTERPROCEDURAL_OPTIMIZATION=ON "${XR_ARGS[@]}"
# PCH can go stale when codegen regenerates headers on first pass; build twice.
cmake --build --preset "$PRESET" || cmake --build --preset "$PRESET"

echo "== [5/5] Staging the release folder =="
cd "$ROOT"
python3 tools/release/package.py --no-windows --linux "$PROJ/out/build/$PRESET" --linux-sdk "$SDK" \
    --out "$ROOT/release" ${REALSTEEL_VERSION:+--version "$REALSTEEL_VERSION"}

echo ""
echo "DONE. Linux package: release/ReCompiledSteel-linux-x64 (and the .tar.gz beside it)."
echo "On the Steam Deck: unpack it in Desktop Mode, run realsteel-setup, add start.sh"
echo "to Steam as a non-Steam game."
