#!/bin/sh
# Regenerates present_spv.h from present_shaders.hlsl, overlay_shaders.hlsl and ao_shaders.hlsl
# (run from the repo root).
DXC=xenosrecompgit/thirdparty/dxc-bin/bin/x64/dxc.exe
D=tools/replayer
$DXC -spirv -T vs_6_0 -E vs_main -Fo $D/present_vs.spv $D/present_shaders.hlsl || exit 1
$DXC -spirv -T ps_6_0 -E ps_main -Fo $D/present_ps.spv $D/present_shaders.hlsl || exit 1
$DXC -spirv -T vs_6_0 -E vs_main -Fo $D/overlay_vs.spv $D/overlay_shaders.hlsl || exit 1
$DXC -spirv -T ps_6_0 -E ps_main -Fo $D/overlay_ps.spv $D/overlay_shaders.hlsl || exit 1
$DXC -spirv -T vs_6_0 -E vs_main -Fo $D/ao_vs.spv $D/ao_shaders.hlsl || exit 1
$DXC -spirv -T ps_6_0 -E ps_main -Fo $D/ao_ps.spv $D/ao_shaders.hlsl || exit 1
$DXC -spirv -T ps_6_0 -E ps_blur -Fo $D/ao_blur_ps.spv $D/ao_shaders.hlsl || exit 1
python - <<'PY'
import struct
out = ['// Generated by build_present_shaders.sh - do not edit.', '#pragma once', '#include <cstdint>']
for name, var in (('present_vs', 'kPresentVSSpv'), ('present_ps', 'kPresentPSSpv'),
                  ('overlay_vs', 'kOverlayVSSpv'), ('overlay_ps', 'kOverlayPSSpv'),
                  ('ao_vs', 'kAoVSSpv'), ('ao_ps', 'kAoPSSpv'), ('ao_blur_ps', 'kAoBlurPSSpv')):
    b = open('tools/replayer/%s.spv' % name, 'rb').read()
    w = struct.unpack('<%dI' % (len(b) // 4), b)
    out.append('static const uint32_t %s[] = {' % var)
    for i in range(0, len(w), 8):
        out.append('  ' + ' '.join('0x%08X,' % x for x in w[i:i + 8]))
    out.append('};')
open('tools/replayer/present_spv.h', 'w').write(chr(10).join(out) + chr(10))
PY
rm -f $D/present_vs.spv $D/present_ps.spv $D/overlay_vs.spv $D/overlay_ps.spv $D/ao_vs.spv $D/ao_ps.spv $D/ao_blur_ps.spv
