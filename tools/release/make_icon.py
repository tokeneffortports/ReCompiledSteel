#!/usr/bin/env python3
"""Draws the ReCompiled Steel icon (our own design: a steel plate with a
teal "RS" in blocky letters) and writes it as a Windows .ico holding PNG
images at 256, 64, 32 and 16 pixels, plus a C header with the same bytes
for the window icon at run time.

  make_icon.py [--ico out.ico] [--header src/realsteel_icon.h]
"""
import os
import struct
import sys
import zlib

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))

# 5 x 7 pixel letters, one string per row.
LETTERS = {
    'R': ['XXXX.', 'X...X', 'X...X', 'XXXX.', 'X.X..', 'X..X.', 'X...X'],
    'S': ['.XXXX', 'X....', 'X....', '.XXX.', '....X', '....X', 'XXXX.'],
}


def draw(size):
    img = np.zeros((size, size, 4), dtype=np.float32)
    y, x = np.mgrid[0:size, 0:size].astype(np.float32)
    cx = cy = (size - 1) / 2.0
    # Rounded square plate, dark steel with a slight vertical gradient.
    r = size * 0.18
    half = size * 0.46
    dx = np.maximum(np.abs(x - cx) - (half - r), 0)
    dy = np.maximum(np.abs(y - cy) - (half - r), 0)
    dist = np.sqrt(dx * dx + dy * dy) - r
    plate = np.clip(0.5 - dist, 0, 1)                     # anti-aliased edge
    shade = 0.16 + 0.10 * (1 - y / size)
    img[..., 0] = shade * 0.75
    img[..., 1] = shade * 0.85
    img[..., 2] = shade * 1.0
    img[..., 3] = plate
    # A rivet in each corner.
    for ry in (0.22, 0.78):
        for rx in (0.22, 0.78):
            d = np.sqrt((x - rx * size) ** 2 + (y - ry * size) ** 2)
            rivet = np.clip(size * 0.035 - d + 0.5, 0, 1)
            img[..., :3] = img[..., :3] * (1 - rivet[..., None]) + rivet[..., None] * np.array([0.42, 0.47, 0.52])
    # The letters, teal, with a soft glow.
    glyph = np.zeros((size, size), dtype=np.float32)
    cell = size * 0.062
    total_w = (5 + 1 + 5) * cell
    x0 = cx - total_w / 2
    y0 = cy - 3.5 * cell
    for li, ch in enumerate('RS'):
        rows = LETTERS[ch]
        for ry, row in enumerate(rows):
            for rx, c in enumerate(row):
                if c != 'X':
                    continue
                px = x0 + (li * 6 + rx) * cell
                py = y0 + ry * cell
                inside = (x >= px) & (x < px + cell + 0.5) & (y >= py) & (y < py + cell + 0.5)
                glyph[inside] = 1.0
    # Cheap blur for the glow: average over a box.
    k = max(1, size // 32)
    pad = np.pad(glyph, k)
    glow = sum(pad[k + oy:k + oy + size, k + ox:k + ox + size] for oy in range(-k, k + 1) for ox in range(-k, k + 1)) / float((2 * k + 1) ** 2)
    teal = np.array([0.30, 0.90, 0.92])
    glow_a = np.clip(glow * 0.9, 0, 1)[..., None]
    img[..., :3] = img[..., :3] * (1 - glow_a) + teal * 0.45 * glow_a
    g = glyph[..., None]
    img[..., :3] = img[..., :3] * (1 - g) + teal * g
    return (np.clip(img, 0, 1) * 255 + 0.5).astype(np.uint8)


def png_bytes(rgba):
    h, w = rgba.shape[:2]
    raw = b''.join(b'\x00' + rgba[yy].tobytes() for yy in range(h))

    def chunk(kind, body):
        return struct.pack('>I', len(body)) + kind + body + struct.pack('>I', zlib.crc32(kind + body) & 0xFFFFFFFF)
    return (b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', w, h, 8, 6, 0, 0, 0)) +
            chunk(b'IDAT', zlib.compress(raw, 9)) + chunk(b'IEND', b''))


def ico_bytes(sizes):
    images = [png_bytes(draw(s)) for s in sizes]
    header = struct.pack('<HHH', 0, 1, len(sizes))
    offset = 6 + 16 * len(sizes)
    entries = b''
    for s, data in zip(sizes, images):
        entries += struct.pack('<BBBBHHII', s if s < 256 else 0, s if s < 256 else 0, 0, 0, 1, 32, len(data), offset)
        offset += len(data)
    return header + entries + b''.join(images)


def main():
    args = sys.argv[1:]
    ico = os.path.join(ROOT, 'src', 'realsteel.ico')
    header = os.path.join(ROOT, 'src', 'realsteel_icon.h')
    while args:
        a = args.pop(0)
        if a == '--ico':
            ico = args.pop(0)
        elif a == '--header':
            header = args.pop(0)
    data = ico_bytes([256, 64, 32, 16])
    open(ico, 'wb').write(data)
    with open(header, 'w', newline='\n') as f:
        f.write('// Generated by tools/release/make_icon.py - the window icon (.ico bytes).\n#pragma once\n#include <cstddef>\n\n')
        f.write('static const unsigned char kRealSteelIcon[] = {\n')
        for i in range(0, len(data), 24):
            f.write('  ' + ', '.join('0x%02X' % b for b in data[i:i + 24]) + ',\n')
        f.write('};\nstatic const size_t kRealSteelIconSize = sizeof(kRealSteelIcon);\n')
    print('wrote %s (%d bytes) and %s' % (ico, len(data), header))
    open(os.path.join(ROOT, 'docs', 'icon_preview.png'), 'wb').write(png_bytes(draw(256)))


if __name__ == '__main__':
    main()
